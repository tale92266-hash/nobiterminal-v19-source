package com.termux.app.nobi;

import android.content.Context;

import com.termux.shared.termux.TermuxConstants;

import java.io.File;
import java.io.FileOutputStream;
import java.nio.charset.StandardCharsets;

/**
 * v7 (49/56/58/60/61/62/64): installs the `nobi` shell bridge into
 * PREFIX/bin so terminal commands can open the editor. Generated at
 * runtime (package + prefix baked in), rewritten only when changed.
 * The script uses `am start` to reach the editor activity; on-device
 * confirmation of that path is still pending.
 */
public final class NobiScriptInstaller {

    private NobiScriptInstaller() {
    }

    public static void installIfNeeded(Context context) {
        try {
            File bin = new File(TermuxConstants.TERMUX_PREFIX_DIR_PATH, "bin");
            if (!bin.isDirectory()) return;
            File script = new File(bin, "nobi");
            String content = buildScript(context.getPackageName(),
                TermuxConstants.TERMUX_PREFIX_DIR_PATH);
            if (script.isFile()) {
                byte[] existing = java.nio.file.Files.readAllBytes(script.toPath());
                if (new String(existing, StandardCharsets.UTF_8).equals(content)) return;
            }
            try (FileOutputStream out = new FileOutputStream(script)) {
                out.write(content.getBytes(StandardCharsets.UTF_8));
            }
            script.setExecutable(true, false);
        } catch (Exception ignored) {
        }
    }

    /** The bashrc hook line (bash only): publishes $PWD for the editor. */
    public static String hookLine(String prefix) {
        return "PROMPT_COMMAND='echo \"$PWD\" > " + prefix
            + "/tmp/nobi-cwd${PROMPT_COMMAND:+;$PROMPT_COMMAND}'";
    }

    private static String buildScript(String pkg, String prefix) {
        String editor = pkg + "/com.nobidev.nobicode.MainActivity";
        StringBuilder s = new StringBuilder();
        s.append("#!/bin/bash\n");
        s.append("# nobi — NobiTerminal editor bridge (generated by the app).\n");
        s.append("PKG=\"").append(pkg).append("\"\n");
        s.append("PREFIX=\"").append(prefix).append("\"\n");
        s.append("EDITOR=\"").append(editor).append("\"\n");
        s.append("AM=/system/bin/am\n");
        s.append("[ -x \"$AM\" ] || AM=am\n");
        s.append("abs() { case \"$1\" in /*) printf '%s' \"$1\";; ~/*) printf '%s/%s' \"$HOME\" \"${1#~/}\";; *) printf '%s/%s' \"$PWD\" \"$1\";; esac; }\n");
        s.append("split_line() {\n");
        s.append("  case \"$1\" in *:[0-9]*)\n");
        s.append("    _line=\"${1##*:}\"; _path=\"${1%:*}\"\n");
        s.append("    case \"$_line\" in *[!0-9]*) _path=\"$1\"; _line=-1;; esac\n");
        s.append("    printf '%s\\n%s\\n' \"$_path\" \"$_line\";;\n");
        s.append("  *) printf '%s\\n-1\\n' \"$1\";; esac\n");
        s.append("}\n");
        s.append("open_editor() { \"$AM\" start -n \"$EDITOR\" \"$@\" >/dev/null 2>&1; }\n");
        s.append("cmd=\"$1\"; shift || true\n");
        s.append("case \"$cmd\" in\n");
        s.append("  edit)\n");
        s.append("    [ $# -ge 1 ] || { echo \"Usage: nobi edit <file>[:line]\"; exit 1; }\n");
        s.append("    _out=\"$(split_line \"$1\")\"; _path=\"$(printf '%s' \"$_out\" | sed -n 1p)\"; _line=\"$(printf '%s' \"$_out\" | sed -n 2p)\"\n");
        s.append("    open_editor --es nobi_open_file_path \"$(abs \"$_path\")\" --ei nobi_open_line \"$_line\" ;;\n");
        s.append("  diff)\n");
        s.append("    [ $# -ge 1 ] || { echo \"Usage: nobi diff <file>\"; exit 1; }\n");
        s.append("    open_editor --es nobi_git_diff_file \"$(abs \"$1\")\" ;;\n");
        s.append("  find)\n");
        s.append("    [ $# -ge 1 ] || { echo \"Usage: nobi find \\\"text\\\"\"; exit 1; }\n");
        s.append("    open_editor --es nobi_search_text \"$*\" ;;\n");
        s.append("  mark)\n");
        s.append("    [ $# -ge 1 ] || { echo \"Usage: nobi mark <file>\"; exit 1; }\n");
        s.append("    open_editor --es nobi_bookmark_path \"$(abs \"$1\")\" ;;\n");
        s.append("  run)\n");
        s.append("    [ $# -ge 1 ] || { echo \"Usage: nobi run <command...>\"; exit 1; }\n");
        s.append("    _out=\"$PREFIX/tmp/nobi-run-output.txt\"\n");
        s.append("    \"$@\" 2>&1 | tee \"$_out\"\n");
        s.append("    open_editor --es nobi_open_file_path \"$_out\" ;;\n");
        s.append("  sync)\n");
        s.append("    _f=\"$PREFIX/tmp/nobi-editor-folder\"\n");
        s.append("    if [ -f \"$_f\" ]; then printf 'cd \"%s\"\\n' \"$(cat \"$_f\")\"; else echo \"No editor folder yet — open a folder in Nobi Code first.\" >&2; exit 1; fi ;;\n");
        s.append("  hook-install)\n");
        s.append("    _line=\"PROMPT_COMMAND='echo \\\"$PWD\\\" > ").append(prefix).append("/tmp/nobi-cwd\\${PROMPT_COMMAND:+;$PROMPT_COMMAND}'\"\n");
        s.append("    grep -Fq \"nobi-cwd\" ~/.bashrc 2>/dev/null || printf '%s\\n' \"$_line\" >> ~/.bashrc\n");
        s.append("    echo \"Hook installed — restart your shell to follow the terminal folder.\" ;;\n");
        s.append("  *) echo \"Usage: nobi edit|diff|find|mark|run|sync|hook-install\" ;;\n");
        s.append("esac\n");
        return s.toString();
    }
}
